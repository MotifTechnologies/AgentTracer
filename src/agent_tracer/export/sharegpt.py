"""Export trajectories to the ShareGPT-style training record schema.

One record per task:

    {
      "source":   {provider: null, name, split, subset, synthetic: {...}},
      "extra":    {task, attempt, steps, usage, missing_tools, error,
                   duration_s, evaluation},
      "category": str | null,
      "conversations": [{role, content, tool_calls?, thinking?}, ...],
      "tools":    [openai function specs]
    }

``source.provider`` is always null: these records are generated by
agent-tracer itself, not ingested from an upstream dataset provider.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any


def _iso_seconds(start: str | None, end: str | None) -> float | None:
    if not start or not end:
        return None
    try:
        delta = datetime.fromisoformat(end) - datetime.fromisoformat(start)
        return round(delta.total_seconds(), 2)
    except ValueError:
        return None


def _to_text(content: Any) -> str | None:
    if content is None or isinstance(content, str):
        return content
    return str(content)


#: Every message carries the same keys, null where a turn has no use for one.
#: Consumers validate against a schema that requires all of them — a system
#: turn without `tool_calls: null` is a schema violation, not a tidier record.
_MESSAGE_KEYS = ("role", "content", "tool_calls", "thinking", "tool_call_id")


def _message(role: str, **fields: Any) -> dict[str, Any]:
    message = dict.fromkeys(_MESSAGE_KEYS)
    message["role"] = role
    message.update(fields)
    return message


def _conversations(traj: dict[str, Any]) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = []
    system_prompt = traj.get("metadata", {}).get("system_prompt")
    if system_prompt:
        messages.append(_message("system", content=system_prompt))

    pending_thinking: list[str] = []
    for event in traj["events"]:
        etype, data = event["event_type"], event["data"]
        if etype == "task":
            content = data.get("content")
            messages.append(_message("user", content=_to_text(content)))
        elif etype == "user_message":
            messages.append(_message("user", content=_to_text(data.get("content"))))
        elif etype == "thinking":
            pending_thinking.append(data["content"])
        elif etype == "model_response":
            msg = _message("assistant", content=data.get("content"))
            tool_calls = [
                {
                    "id": tc.get("tool_call_id"),
                    "type": "function",
                    "function": {
                        "name": tc.get("name"),
                        "arguments": (
                            tc["arguments"]
                            if isinstance(tc.get("arguments"), str)
                            else json.dumps(tc.get("arguments"), ensure_ascii=False)
                        ),
                    },
                }
                for tc in data.get("tool_calls", [])
            ]
            msg["tool_calls"] = tool_calls or None
            if pending_thinking:
                msg["thinking"] = "\n\n".join(pending_thinking)
                pending_thinking = []
            messages.append(msg)
        elif etype == "tool_result":
            messages.append(
                _message(
                    "tool",
                    content=_to_text(data.get("content")),
                    tool_call_id=data.get("tool_call_id"),
                )
            )
    return messages


def trajectory_to_record(
    traj: dict[str, Any],
    *,
    name: str = "agent-tracer",
    split: str = "train",
    subset: str | None = None,
    category: str | None = None,
) -> dict[str, Any]:
    metadata = traj.get("metadata", {})
    result = traj.get("result", {})
    tokens = metadata.get("total_tokens", {})
    prompt_tokens = tokens.get("input", 0)
    completion_tokens = tokens.get("reasoning", 0) + tokens.get("answer", 0)
    steps = sum(1 for e in traj["events"] if e["event_type"] == "model_response")

    return {
        "source": {
            "provider": None,
            "name": name,
            "split": split,
            "subset": subset,
            "synthetic": {
                "synth": True,
                "model": metadata.get("model", {}).get("model_name"),
                "effort": metadata.get("model", {}).get("reasoning_effort"),
                "ground_truth": "reference" if result.get("evaluation") else None,
                "system_prompt": metadata.get("system_prompt"),
            },
        },
        "extra": {
            "task": traj["task_id"],
            "sample_idx": traj.get("sample_idx", 0),
            "attempt": result.get("attempt", 1),
            "steps": steps,
            "usage": {
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": prompt_tokens + completion_tokens,
            },
            "missing_tools": [],
            "error": result.get("error"),
            "duration_s": _iso_seconds(
                metadata.get("timestamp_start"), metadata.get("timestamp_end")
            ),
            "evaluation": result.get("evaluation"),
            "exit_status": result.get("exit_status"),
        },
        "category": category,
        "conversations": _conversations(traj),
        "tools": metadata.get("tools", []),
    }


class UngradedTrajectoryError(ValueError):
    """Raised when a selection option needs a verdict the trajectory lacks."""


def _verdict(record: dict[str, Any]) -> bool:
    """The recorded correctness, or an error if there is none.

    Selecting on correctness when correctness is unknown would quietly keep or
    drop records on a coin flip, so an ungraded trajectory aborts the export
    rather than being guessed at.
    """
    evaluation = record["extra"].get("evaluation") or {}
    correct = evaluation.get("correct")
    if correct is None:
        raise UngradedTrajectoryError(
            f"{record['extra']['task']} (sample {record['extra']['sample_idx']}): "
            "no correctness verdict — --require-correct/--best-per-task cannot "
            "select on it. Export without those options, or use a dataset that grades."
        )
    return bool(correct)


def _cost(record: dict[str, Any]) -> tuple[int, int, int]:
    """Rank successful samples: fewest steps, then fewest tokens, then stable."""
    return (
        record["extra"]["steps"],
        record["extra"]["usage"]["total_tokens"],
        record["extra"]["sample_idx"],
    )


def select_records(
    records: list[dict[str, Any]],
    *,
    require_correct: bool = False,
    best_per_task: bool = False,
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """Apply rejection sampling. Returns (kept, stats)."""
    if not (require_correct or best_per_task):
        return records, {}

    correct = [r for r in records if _verdict(r)]
    stats = {"dropped_incorrect": len(records) - len(correct)}

    if not best_per_task:
        return correct, stats

    # One record per task: the shortest correct rollout. A task with no correct
    # rollout has nothing to keep, and is counted rather than passed through.
    best: dict[str, dict[str, Any]] = {}
    for record in correct:
        task = record["extra"]["task"]
        if task not in best or _cost(record) < _cost(best[task]):
            best[task] = record
    tasks_seen = {r["extra"]["task"] for r in records}
    stats["dropped_extra_samples"] = len(correct) - len(best)
    stats["tasks_without_a_correct_sample"] = len(tasks_seen) - len(best)
    return [best[k] for k in sorted(best)], stats


def load_records(
    trajectory_dir: Path,
    *,
    name: str = "agent-tracer",
    split: str = "train",
    subset: str | None = None,
    category: str | None = None,
    include_errors: bool = False,
    require_correct: bool = False,
    best_per_task: bool = False,
) -> tuple[list[dict[str, Any]], int, dict[str, int]]:
    """Convert every ``*.traj.json`` into a record. Returns (records, skipped, stats)."""
    records: list[dict[str, Any]] = []
    skipped = 0
    for path in sorted(trajectory_dir.glob("*.traj.json")):
        traj = json.loads(path.read_text("utf-8"))
        if not include_errors and traj.get("result", {}).get("exit_status") == "error":
            skipped += 1
            continue
        records.append(
            trajectory_to_record(traj, name=name, split=split, subset=subset, category=category)
        )
    records, stats = select_records(
        records, require_correct=require_correct, best_per_task=best_per_task
    )
    return records, skipped, stats


def export_directory(
    trajectory_dir: Path,
    output_path: Path,
    **kwargs: Any,
) -> tuple[int, int]:
    """Write ShareGPT records as JSONL. Returns (written, skipped)."""
    records, skipped, _ = load_records(trajectory_dir, **kwargs)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as out:
        for record in records:
            out.write(json.dumps(record, ensure_ascii=False) + "\n")
    return len(records), skipped
