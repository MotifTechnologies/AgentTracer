"""Reading and editing .xlsx workbooks in the task's sandbox.

Launched by the runner as declared in mcp.json:
    uv run --quiet server.py    (stdio transport)

`soffice` converts a workbook to CSV, which loses the sheets, the formulas and
the cell addresses — everything a question about a spreadsheet is usually about.
This keeps them.

Same shape as `pdf`: the file is read out of the sandbox (`environments.read_bytes`,
base64 over `exec`), openpyxl runs in this process where it is declared, and the
sandbox only has to produce bytes. `write_cells` sends the workbook back.

Two things about spreadsheets that produce confidently wrong answers, and what
is done about each:

**A formula's value is not in the file.** openpyxl reads either the formula or
the value the last spreadsheet application cached there, never both at once —
and for a workbook generated by a script and never opened, the cache is empty.
Ask for values and every computed cell comes back `None`, which reads as "the
cell is blank" rather than "nobody has evaluated this". So both are read and
returned together, and a formula with no cached value is called out.

**A round trip is lossy.** openpyxl rebuilds the file it writes. Charts, images,
shapes and text boxes, pivot tables, .xlsm macros and sheet-level extensions
(sparklines, x14 data validation) do not survive it, and most of them never
reach openpyxl's object model at all — so the guard reads the file's own parts
rather than asking the workbook. `write_cells` refuses outright when any is
present. Cell comments *do* survive; the docstring used to promise a refusal
for them, which was a documentation error rather than a missing check.

The one loss that cannot be refused is the formula cache: saving writes `<v/>`
for every formula openpyxl did not evaluate, so a workbook a spreadsheet
application had computed loses those values across every sheet, and a later
`read_range` calls it "a workbook never opened by a spreadsheet application" —
a claim the write just made true. Refusing on it would refuse the ordinary
case, so it is reported instead.
"""

import datetime as dt
import io
import re

from mcp.server import MCPServer

from agent_tracer.environments import from_env, read_bytes, resolve, write_bytes

mcp = MCPServer(name="xlsx", version="0.1.0")

DEFAULT_TIMEOUT_S = 120

#: A full sheet can be a million cells. The reply says when it truncated.
#:
#: Counted against every coordinate *visited*, not against the cells that reach
#: the reply. Counting only the latter is what let a 4.8 KB workbook holding
#: just A1 and CZ20000 cost gigabytes: the 2.08 million empty coordinates
#: between them were skipped without being counted, and openpyxl had already
#: instantiated a Cell for each of them.
MAX_CELLS_PER_CALL = 2000

#: `find_cells` walks cells instead of returning them, so it gets a much larger
#: budget — but a bounded one, and it says when it ran out. A used range
#: reaching CZ200000 is 20.8 million coordinates.
MAX_CELLS_SCANNED = 1_000_000

_SANDBOX = None


def _sandbox():
    """The sandbox and its working directory, opened once and reused."""
    global _SANDBOX
    if _SANDBOX is None:
        _SANDBOX = from_env()
    return _SANDBOX


def _load(path: str) -> tuple[str, bytes]:
    access, workdir = _sandbox()
    target = resolve(path, workdir)
    return target, read_bytes(access, target, timeout_s=DEFAULT_TIMEOUT_S)


def _workbook(raw: bytes, *, data_only: bool, read_only: bool = False):
    """Open the workbook.

    `read_only` for anything that walks cells. Outside read-only mode openpyxl
    builds a Cell object for every coordinate in the used range as soon as
    `iter_rows` touches it, which is unbounded in the file's *extent* rather
    than in its size. `list_sheets` needs `.dimensions` and `write_cells` needs
    to write, and neither is available read-only.
    """
    import openpyxl
    from openpyxl.utils.exceptions import InvalidFileException

    try:
        return openpyxl.load_workbook(
            io.BytesIO(raw), data_only=data_only, read_only=read_only
        )
    except InvalidFileException as exc:
        raise ValueError(
            f"Not a readable .xlsx workbook: {exc}. openpyxl does not read the older "
            ".xls format — convert it with soffice first."
        ) from exc
    except Exception as exc:  # zipfile/xml/KeyError all mean "this is not a workbook"
        raise ValueError(
            f"Could not open the workbook: {type(exc).__name__}: {exc}"
        ) from exc


def _sheet(workbook, name: str | None):
    if name is None:
        return workbook[workbook.sheetnames[0]]
    if name not in workbook.sheetnames:
        raise ValueError(
            f"No sheet named {name!r}. This workbook has: {', '.join(workbook.sheetnames)}"
        )
    return workbook[name]


#: Parts whose presence means a save would drop something, by name prefix.
#:
#: Read off the file because openpyxl's object model does not carry any of it:
#: a workbook with macros or a pivot table loaded clean, saved clean and
#: reported success. `drawing` rather than the whole `xl/drawings/` folder
#: because a cell comment's VML lives there too — and comments *do* survive.
_LOSSY_PARTS = (
    ("xl/vbaProject.bin", "macros (openpyxl loads with keep_vba=False)"),
    ("xl/pivotCache/", "pivot tables"),
    ("xl/pivotTables/", "pivot tables"),
    ("xl/drawings/drawing", "drawings — charts, images, shapes or text boxes"),
)

#: A sheet-level `<extLst>` carries sparklines and x14 data validation, and
#: openpyxl writes neither back.
_SHEET_EXTENSION = re.compile(rb"<extLst[ >/]")

#: `<f>A1*B1</f><v>42</v>` — a formula and the value something computed for it.
#: Saving writes `<v/>` in its place. The second alternative is a shared
#: formula, whose `<f>` is self-closing on every cell but the first.
_CACHED_VALUE = re.compile(rb"</f>\s*<v[ >]|<f[^>]*/>\s*<v[ >]")


def _scan(archive, part: str, pattern) -> bool:
    """Search one zip member without holding it in memory.

    A sheet's XML runs to hundreds of megabytes decompressed, which is exactly
    what `read_range` is careful not to do.
    """
    tail = b""
    with archive.open(part) as stream:
        while block := stream.read(1 << 20):
            if pattern.search(tail + block):
                return True
            tail = block[-256:]
    return False


def _losses(raw: bytes, workbook) -> tuple[list[str], bool]:
    """What saving this workbook would silently drop, and whether it would clear
    the formula cache.

    The first is a refusal; the second is not. Every workbook a spreadsheet
    application has ever saved has cached values, so refusing on them would
    refuse the ordinary case — but it has to be said, because the loss is
    invisible until a later `read_range` calls the file "never opened by a
    spreadsheet application".
    """
    import zipfile

    losses = []
    for name in workbook.sheetnames:
        page = workbook[name]
        if getattr(page, "_charts", None):
            losses.append(f"{name}: {len(page._charts)} chart(s)")
        if getattr(page, "_images", None):
            losses.append(f"{name}: {len(page._images)} image(s)")

    # The counts above already name every chart and image, so the drawings part
    # only needs to speak when they do not — that is the shape or the text box,
    # which openpyxl does not model at all.
    skip = {"xl/drawings/drawing"} if losses else set()

    cached = False
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        parts = archive.namelist()
        for prefix, what in _LOSSY_PARTS:
            if prefix in skip or what in losses:
                continue
            if any(part.startswith(prefix) for part in parts):
                losses.append(what)
        sheets = [part for part in parts if part.startswith("xl/worksheets/sheet")]
        if any(_scan(archive, part, _SHEET_EXTENSION) for part in sheets):
            losses.append("sheet extensions — sparklines, x14 data validation")
        cached = any(_scan(archive, part, _CACHED_VALUE) for part in sheets)
    return losses, cached


def _extent(sheet) -> tuple[int, int]:
    """How far the sheet goes, without trusting a `<dimension>` that is absent."""
    if sheet.max_row is None or sheet.max_column is None:
        sheet.calculate_dimension(force=True)
    return sheet.max_row or 1, sheet.max_column or 1


def _window(
    sheet, cell_range: str | None, budget: int
) -> tuple[tuple[int, int, int, int], bool]:
    """The rectangle to visit, clipped to `budget` coordinates.

    Derived before anything is read, so an explicit "A1:CZ20000" costs no more
    than the default extent does. Returns (top, left, bottom, right) 1-based and
    inclusive, and whether the clip lost anything.
    """
    from openpyxl.utils import range_boundaries

    rows, columns = _extent(sheet)
    if cell_range:
        try:
            left, top, right, bottom = range_boundaries(cell_range)
        except ValueError as exc:
            raise ValueError(f"Could not read range {cell_range!r}: {exc}") from exc
        # An open range ("A:C", "2:5") leaves the other axis unbounded.
        top, left = top or 1, left or 1
        bottom, right = bottom or rows, right or columns
        if bottom < top or right < left:
            raise ValueError(
                f"Could not read range {cell_range!r}: it ends before it starts"
            )
    else:
        top, left, bottom, right = 1, 1, rows, columns

    width = min(right - left + 1, budget)
    height = min(bottom - top + 1, max(1, budget // width))
    return (top, left, top + height - 1, left + width - 1), (
        height < bottom - top + 1 or width < right - left + 1
    )


def _jsonable(value):
    """Dates and times are not JSON; everything else openpyxl yields is."""
    if isinstance(value, dt.datetime):
        return value.isoformat(sep=" ", timespec="seconds")
    if isinstance(value, (dt.date, dt.time)):
        return value.isoformat()
    if isinstance(value, dt.timedelta):
        return value.total_seconds()
    return value


@mcp.tool()
def list_sheets(path: str) -> dict:
    """List a workbook's sheets, with the extent of each.

    Worth calling first: `read_range` defaults to the first sheet, and this says
    what the others are called and how far they go.

    Args:
        path: .xlsx file, absolute or relative to the working directory.
    """
    target, raw = _load(path)
    workbook = _workbook(raw, data_only=False)

    sheets = []
    for name in workbook.sheetnames:
        sheet = workbook[name]
        sheets.append(
            {
                "name": name,
                "rows": sheet.max_row,
                "columns": sheet.max_column,
                "dimensions": sheet.dimensions,
                "hidden": sheet.sheet_state != "visible",
            }
        )
    return {"path": target, "sheets": sheets, "count": len(sheets)}


@mcp.tool()
def read_range(
    path: str, sheet: str | None = None, cell_range: str | None = None
) -> dict:
    """Read cells, with both their formulas and their computed values.

    At most `MAX_CELLS_PER_CALL` coordinates are visited, empty ones included,
    so a wide sheet comes back as few rows. `range` says which rectangle was
    read and `truncated` whether anything was left; ask again with a narrower
    `cell_range` to get the rest.

    Args:
        path: .xlsx file, absolute or relative to the working directory.
        sheet: Sheet name. Defaults to the first sheet.
        cell_range: A1-style range, e.g. "A1:D20". Defaults to the used extent.
    """
    from openpyxl.utils import get_column_letter

    target, raw = _load(path)
    formulas = _workbook(raw, data_only=False, read_only=True)
    values = _workbook(raw, data_only=True, read_only=True)
    try:
        formula_sheet = _sheet(formulas, sheet)
        value_sheet = _sheet(values, sheet)
        (top, left, bottom, right), truncated = _window(
            formula_sheet, cell_range, MAX_CELLS_PER_CALL
        )
        box = {"min_row": top, "min_col": left, "max_row": bottom, "max_col": right}

        cells, uncomputed = [], 0
        rows = zip(
            formula_sheet.iter_rows(**box), value_sheet.iter_rows(**box), strict=False
        )
        for number, (frow, vrow) in enumerate(rows, start=top):
            for letter, (fcell, vcell) in enumerate(
                zip(frow, vrow, strict=False), start=left
            ):
                if fcell.value is None and vcell.value is None:
                    continue
                is_formula = isinstance(fcell.value, str) and fcell.value.startswith(
                    "="
                )
                if is_formula and vcell.value is None:
                    uncomputed += 1
                cells.append(
                    {
                        # Built from the indices: read-only mode hands back a
                        # shared EmptyCell for a gap, which has no coordinate.
                        "ref": f"{get_column_letter(letter)}{number}",
                        "value": _jsonable(vcell.value),
                        "formula": fcell.value if is_formula else None,
                    }
                )
        title = formula_sheet.title
    finally:
        formulas.close()
        values.close()

    return {
        "path": target,
        "sheet": title,
        # What was actually looked at. Without it a reply of one cell and
        # `truncated: true` says nothing about where to ask next.
        "range": f"{get_column_letter(left)}{top}:{get_column_letter(right)}{bottom}",
        "cells": cells,
        "count": len(cells),
        # The window was clipped, not the reply: the cap counts every coordinate
        # visited, so a sheet that is mostly empty still truncates.
        "truncated": truncated,
        # The trap this server exists to close: a formula whose value is None
        # has not been evaluated by anything, and is not an empty cell.
        "note": (
            f"{uncomputed} formula cells have no computed value — this workbook has not been "
            "opened by a spreadsheet application, so nothing has evaluated them. Their "
            "`value` is null because it was never calculated, not because the cell is empty. "
            "Work them out from the formulas and the inputs."
            if uncomputed
            else None
        ),
    }


@mcp.tool()
def find_cells(
    path: str, pattern: str, sheet: str | None = None, max_results: int = 50
) -> dict:
    """Find cells whose value or formula contains a string.

    For locating a label or figure without reading the whole sheet.

    Args:
        path: .xlsx file, absolute or relative to the working directory.
        pattern: Literal text to look for, case-insensitive. Not a regex.
        sheet: Limit to one sheet. Defaults to every sheet.
        max_results: Stop after this many matches.
    """
    if max_results < 1:
        raise ValueError("max_results must be >= 1")

    from openpyxl.utils import get_column_letter

    target, raw = _load(path)
    formulas = _workbook(raw, data_only=False, read_only=True)
    values = _workbook(raw, data_only=True, read_only=True)
    needle = pattern.lower()

    names = [_sheet(formulas, sheet).title] if sheet else formulas.sheetnames
    matches, scanned, exhausted = [], 0, False
    try:
        for name in names:
            if exhausted or len(matches) >= max_results:
                break
            fsheet, vsheet = formulas[name], values[name]
            rows, columns = _extent(fsheet)
            box = {"max_row": rows, "max_col": columns}
            paired = zip(fsheet.iter_rows(**box), vsheet.iter_rows(**box), strict=False)
            for number, (frow, vrow) in enumerate(paired, start=1):
                if exhausted or len(matches) >= max_results:
                    break
                for letter, (fcell, vcell) in enumerate(
                    zip(frow, vrow, strict=False), start=1
                ):
                    if len(matches) >= max_results:
                        break
                    if scanned >= MAX_CELLS_SCANNED:
                        exhausted = True
                        break
                    scanned += 1
                    haystacks = [fcell.value, vcell.value]
                    if any(
                        h is not None and needle in str(h).lower() for h in haystacks
                    ):
                        is_formula = isinstance(
                            fcell.value, str
                        ) and fcell.value.startswith("=")
                        matches.append(
                            {
                                "sheet": name,
                                "ref": f"{get_column_letter(letter)}{number}",
                                "value": _jsonable(vcell.value),
                                "formula": fcell.value if is_formula else None,
                            }
                        )
    finally:
        formulas.close()
        values.close()

    return {
        "path": target,
        "pattern": pattern,
        "matches": matches,
        "count": len(matches),
        "truncated": exhausted or len(matches) >= max_results,
        # Two different reasons to stop, and they call for different next moves.
        "note": (
            f"stopped after scanning {scanned} cells without reaching the end of the "
            "workbook — search one sheet at a time, or narrow the range with read_range."
            if exhausted
            else None
        ),
    }


@mcp.tool()
def write_cells(
    path: str,
    cells: dict[str, str | int | float | bool | None],
    sheet: str | None = None,
) -> dict:
    """Set specific cells in an existing workbook, leaving the rest alone.

    Writing rebuilds the whole file, so it refuses when the workbook holds
    anything that would not survive that: charts, images, shapes or text boxes,
    pivot tables, .xlsm macros, or sheet-level extensions (sparklines, x14 data
    validation). Use `code_exec` if that trade is acceptable for a task. Cell
    comments do survive and are not refused.

    One loss is not refusable and is reported instead. Saving clears every
    cached formula value in the workbook — openpyxl writes `<v/>` for a formula
    it did not evaluate — so a workbook a spreadsheet application had computed
    comes back with `value: null` on every formula cell, everywhere, not only on
    the sheet edited. `cleared_formula_cache` says when that happened.

    A value beginning with "=" is stored as a formula. It will have no computed
    value until a spreadsheet application opens the file — `read_range` says so
    when that is the case.

    Args:
        path: .xlsx file, absolute or relative to the working directory.
        cells: A1-style references to values, e.g. {"B2": 4200, "C1": "total"}.
        sheet: Sheet name. Defaults to the first sheet.
    """
    if not cells:
        raise ValueError('No cells given — pass at least one, e.g. {"B2": 4200}')

    access, workdir = _sandbox()
    target = resolve(path, workdir)
    raw = read_bytes(access, target, timeout_s=DEFAULT_TIMEOUT_S)
    workbook = _workbook(raw, data_only=False)
    target_sheet = _sheet(workbook, sheet)

    # Checked across the whole workbook, not just the sheet being edited: the
    # save rewrites the entire file.
    casualties, cleared_cache = _losses(raw, workbook)
    if casualties:
        raise ValueError(
            "Refusing to write: saving rebuilds the workbook and would silently drop "
            f"{'; '.join(casualties)}. Edit it with code_exec if losing them is acceptable."
        )

    written = []
    for ref, value in cells.items():
        try:
            target_sheet[ref] = value
        except (ValueError, TypeError, KeyError) as exc:
            raise ValueError(f"Could not write {ref!r}: {exc}") from exc
        written.append(ref)

    buffer = io.BytesIO()
    workbook.save(buffer)
    write_bytes(access, target, buffer.getvalue(), timeout_s=DEFAULT_TIMEOUT_S)

    return {
        "path": target,
        "sheet": target_sheet.title,
        "written": sorted(written),
        "count": len(written),
        "size_bytes": buffer.tell(),
        "cleared_formula_cache": cleared_cache,
        "note": (
            "Every cached formula value in this workbook is now gone — openpyxl writes "
            "<v/> for a formula it has not evaluated, and saving rebuilds the whole file, "
            "not just the sheet edited. read_range will report those cells as uncomputed "
            "until a spreadsheet application opens this file again."
            if cleared_cache
            else None
        ),
    }


if __name__ == "__main__":
    mcp.run(transport="stdio")
